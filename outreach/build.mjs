function libsFor(names) {
  const need = new Set();
  const visit = n => { if (need.has(n)) return; LIB_DEPS[n].forEach(visit); need.add(n); };
  names.forEach(visit);
  return ORDER.filter(n => need.has(n)).map(n => readFileSync(join(here, 'lib', `${n}.js`), 'utf8')).join('\n');
}
