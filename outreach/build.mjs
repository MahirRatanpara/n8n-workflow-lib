// Scraper patch (idempotent): companyId on every saved job, /p commands in the
// digest, and the correct "next scan" interval.
// ═════════════════════════════════════════════════════════════════════════════
const START = '// >>> outreach company resolver (generated by outreach/build.mjs, do not edit inside)';
const END = '// <<< outreach company resolver';
function patchScraper() {
  const file = join(ROOT, 'Linkedin Job Search v3.json');
  const wf = JSON.parse(readFileSync(file, 'utf8'));
  const node = name => { const n = wf.nodes.find(x => x.name === name); if (!n) throw new Error(`scraper node ${name} not found`); return n; };

  const pas = node('Parse All Scores');
  let js = pas.parameters.jsCode;
  const block = `${START}\n${libsFor(['company'])}\nconst __companyIndex = (() => { try { return buildCompanyIndex($('Get Companies').all().map(i => i.json)); } catch (e) { return null; } })();\nfunction __companyIdOf(name) { return __companyIndex ? resolveCompany(__companyIndex, name) : ''; }\n${END}\n`;
  if (js.includes(START)) js = js.slice(0, js.indexOf(START)) + block + js.slice(js.indexOf(END) + END.length + 1);
  else js = block + js;
  if (!js.includes('companyId: __companyIdOf(job.company)')) {
    const anchor = '      company: job.company,\n';
    if (!js.includes(anchor)) throw new Error('Parse All Scores: anchor not found');
    js = js.replace(anchor, anchor + '      companyId: __companyIdOf(job.company),\n');
  }
  pas.parameters.jsCode = js;

  // Map columns by header name ("Map Automatically"). The manual mapping keeps
  // a snapshot of the sheet's columns, and n8n refuses to write ("Column names
  // were updated after the node's setup") whenever the sheet changes, e.g. when
  // setup adds outreach columns or you add your own. Auto-mapping writes each
  // item field to the column with the same header, leaves other columns
  // (isPriority, outreachStatus, ...) untouched and ignores fields with no
  // column (highMatch, scoreSummary).
  for (const name of ['Save All to Sheet', 'Save Low Match']) {
    const p = node(name).parameters;
    p.columns = { mappingMode: 'autoMapInputData', value: {}, matchingColumns: ['jobid'], schema: [], attemptToConvertTypes: false, convertFieldsToString: false };
    p.options = { ...(p.options || {}), handlingExtraData: 'ignoreIt' };
  }

  const fs = node('Format Summary');
  let f = fs.parameters.jsCode;
  const linkLine = 'block += `\\u{1F517} [Apply on LinkedIn](${job.applyLink})\\n\\n`;';
  if (f.includes(linkLine)) {
    f = f.replace(linkLine, 'block += `\\u{1F517} [Apply on LinkedIn](${job.applyLink})\\n`;\n  block += `\\u{2B50} Priority: /p${job.jobid}\\n\\n`;');
  } else if (!f.includes('Priority: /p${job.jobid}')) throw new Error('Format Summary: apply-link anchor not found');
  fs.parameters.jsCode = f.replaceAll('Next scan in ~6 hours', 'Next scan in ~3 hours');
  const fn = node('Format No Jobs');
  fn.parameters.jsCode = fn.parameters.jsCode.replaceAll('Next scan in ~6 hours', 'Next scan in ~3 hours');
  const st = node('Sticky Note');
  st.parameters.content = st.parameters.content.replace('Workflow runs every 6 hours.', 'Workflow runs every 3 hours.');

  writeFileSync(file, JSON.stringify(wf, null, 2) + '\n');
  return file;
}

