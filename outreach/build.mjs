class Workflow {
  constructor(key, name) { this.id = IDS[key]; this.name = name; this.nodes = []; this.connections = {}; }
  add(node, x, y) { this.nodes.push({ id: uuid(`${this.id}:${node.name}`), position: [x, y], ...node }); return node.name; }
  link(from, to, out = 0, type = 'main') {
    const c = (this.connections[from] = this.connections[from] || {});
    const outs = (c[type] = c[type] || []);
    while (outs.length <= out) outs.push([]);
    outs[out].push({ node: to, type, index: 0 });
  }
  chain(...names) { for (let i = 0; i < names.length - 1; i++) this.link(names[i], names[i + 1]); }
  toJSON() {
    const names = new Set(this.nodes.map(n => n.name));
    for (const [from, c] of Object.entries(this.connections)) {
      if (!names.has(from)) throw new Error(`${this.name}: unknown source ${from}`);
      for (const outs of Object.values(c)) for (const o of outs) for (const t of o) if (!names.has(t.node)) throw new Error(`${this.name}: unknown target ${t.node}`);
    }
    return {
      name: this.name, nodes: this.nodes, pinData: {}, connections: this.connections, active: false,
      settings: {
        executionOrder: 'v1', binaryMode: 'separate', timezone: 'Asia/Kolkata', saveManualExecutions: true,
        ...(this.id !== IDS.error ? { errorWorkflow: IDS.error } : {}),
      },
      versionId: uuid(`${this.id}:${JSON.stringify(this.nodes).length}`), meta: { templateCredsSetupCompleted: true },
      id: this.id, tags: [],
    };
  }
}

