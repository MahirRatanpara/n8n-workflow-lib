function code(name, body, { libs = ['util'], each = false, ...opts } = {}) {
  return {
    name, type: 'n8n-nodes-base.code', typeVersion: 2,
    parameters: { ...(each ? { mode: 'runOnceForEachItem' } : {}), jsCode: `${BANNER}${libsFor(libs)}\n\n// ── node logic ──\n${body.trim()}\n` },
    ...opts,
  };
}
function http(name, { method = 'GET', url, cred = 'sheets', body, retry = true, ...opts }) {
  const auth = cred === 'fullenrich'
    ? { authentication: 'genericCredentialType', genericAuthType: 'httpBearerAuth' }
    : cred ? { authentication: 'predefinedCredentialType', nodeCredentialType: CRED_TYPE[cred] } : {};
  return {
    name, type: 'n8n-nodes-base.httpRequest', typeVersion: 4.2,
    parameters: {
      method, url, ...auth,
      ...(body ? { sendBody: true, specifyBody: 'json', jsonBody: body } : {}),
      options: {},
    },
    ...(cred ? { credentials: CRED[cred] } : {}),
    ...(retry ? { retryOnFail: true, maxTries: 3, waitBetweenTries: 3000 } : {}),
    ...opts,
  };
}
function iff(name, expr) {
  return {
    name, type: 'n8n-nodes-base.if', typeVersion: 2.3,
    parameters: {
      conditions: {
        options: { caseSensitive: true, leftValue: '', typeValidation: 'loose', version: 3 },
        conditions: [{ id: uuid(`if-${name}`), leftValue: C(expr), rightValue: '', operator: { type: 'boolean', operation: 'true', singleValue: true } }],
        combinator: 'and',
      },
      looseTypeValidation: true, options: {},
    },
  };
}
// n8n's Telegram node parses Markdown unless told otherwise; our messages are
